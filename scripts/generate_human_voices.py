async def generate_one(sem, text, voice, rate, pitch, out_path):
    if not FORCE_REGEN and os.path.exists(out_path) and os.path.getsize(out_path) > 500:
        return "skipped"
    async with sem:
        for attempt in range(3):
            try:
                communicate = edge_tts.Communicate(text=text, voice=voice, rate=rate, pitch=pitch)
                await communicate.save(out_path)
                if os.path.exists(out_path) and os.path.getsize(out_path) > 500:
                    return "generated"
            except Exception as e:
                if attempt == 2:
                    print(f"[ERR] {out_path}: {e}")
                    return "failed"
                await asyncio.sleep(1.2)
    return "failed"


async def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    sem = asyncio.Semaphore(CONCURRENCY)
    tasks = []
    manifest = {"version": "2.0-edge-neural", "personas": {}}

    for pid, cfg in PERSONA_VOICES.items():
        style = cfg["style"]
        bank = STYLE_BANKS.get(style, STYLE_BANKS["friendly"])
        manifest["personas"][pid] = {}

        persona_tags = {
            "buddy": ("", ""),
            "lolo": ("", ""),
            "noor": ("", ""),
            "chef": ("", ""),
            "pastry": ("", ""),
            "athlete": ("", ""),
            "sheikh": ("", ""),
            "friend_saad": ("", ""),
            "coach_sakhr": ("", ""),
            "grand_chef": ("", ""),
            "princess_layla": ("", ""),
            "butler_farid": ("", ""),
            "friend_fadi": ("", ""),
            "anime_zain": ("", ""),
            "anime_ryu": ("", ""),
            "anime_ritaj": ("", "")
        }
        p_pre, p_suf = persona_tags.get(pid, ("", ""))

        for intent, phrases in bank.items():
            manifest["personas"][pid][intent] = []
            for idx, base_text in enumerate(phrases, start=1):
                text = base_text
                if idx == 2 and p_pre:
                    text = p_pre + base_text
                elif idx == 3 and p_suf:
                    text = base_text.rstrip(".؟!") + p_suf
                fname = f"{pid}_{intent}_{idx}.mp3"
                rel_path = f"{OUT_DIR}/{fname}"
                manifest["personas"][pid][intent].append({"text": text, "file": rel_path})
                tasks.append(generate_one(sem, text, cfg["voice"], cfg["rate"], cfg["pitch"], rel_path))

        # الجمل الخاصة بالشخصية
        if pid in EXTRA_PERSONA_CLIPS:
            manifest["personas"][pid]["special"] = []
            for key_name, text in EXTRA_PERSONA_CLIPS[pid]:
                fname = f"{pid}_{key_name}.mp3"
                rel_path = f"{OUT_DIR}/{fname}"
                manifest["personas"][pid]["special"].append({"text": text, "file": rel_path})
                tasks.append(generate_one(sem, text, cfg["voice"], cfg["rate"], cfg["pitch"], rel_path))

    results = await asyncio.gather(*tasks)
    gen_cnt = results.count("generated")
    skip_cnt = results.count("skipped")
    fail_cnt = results.count("failed")

    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)

    print(f"Done! Total: {len(tasks)} | Generated: {gen_cnt} | Skipped: {skip_cnt} | Failed: {fail_cnt}")


if __name__ == "__main__":
    asyncio.run(main())
